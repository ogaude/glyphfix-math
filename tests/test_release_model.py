def test_card_class_counts_match_the_published_results():
    import json
    from pathlib import Path

    results = Path("evidence/acceptance/results.json")
    if not results.is_file():
        pytest.skip("published results.json not present")
    stock = {c["class"]: c["stock_errors"] for c in json.loads(results.read_text())["per_class"]}
    text = Path("release_templates/model_card.md").read_text().replace("\n", " ")
    for cls, label in (("prime_l", "read as l (1)"), ("greek_latin", "Latin (18)"), ("i_1", "1 (3)"), ("dropped_prime", "flagged 31 rows")):
        assert label in text, cls
    assert (stock["prime_l"], stock["greek_latin"], stock["i_1"], stock["dropped_prime"]) == (1, 18, 3, 31)
