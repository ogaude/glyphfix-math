def test_modelfile_relative_from_and_identical_rest():
    out = sm.make_modelfile(SOURCE)
    assert out.splitlines() == [
        "FROM ./text-q8_0.gguf",
        "FROM ./mmproj-stock-q8_0.gguf",
        "TEMPLATE {{ .Prompt }}",
        "PARAMETER num_ctx 32768",
        "PARAMETER num_predict 24576",
    ]
    assert "/abs" not in out and "#" not in out


@pytest.mark.parametrize("n", [1, 3])
def test_modelfile_wrong_from_count_raises(n):
    src = "".join(f"FROM /x/{i}\n" for i in range(n)) + "TEMPLATE {{ .Prompt }}\n"
    with pytest.raises(sm.StageError):
        sm.make_modelfile(src)


def test_copy_verified(tmp_path):
    src = tmp_path / "a.bin"
    src.write_bytes(b"x" * (3 << 20) + b"tail")
    good = hashlib.sha256(src.read_bytes()).hexdigest()
    assert sm.copy_verified(src, tmp_path / "out" / "a.bin", good) == good
    assert (tmp_path / "out" / "a.bin").read_bytes() == src.read_bytes()
    with pytest.raises(sm.StageError):
        sm.copy_verified(src, tmp_path / "out" / "bad.bin", "0" * 64)
    assert not (tmp_path / "out" / "bad.bin").exists()


def test_model_card_front_matter_and_body():
    tpl = (ROOT / "release_templates/model_card.md").read_text()
    table = [("text-q8_0.gguf", 10, "cd" * 32)]
    card = sm.render_model_card(tpl, _results(), _entry(), table, sm.make_modelfile(SOURCE), train_rows=8000)
    front = card.split("---")[1]
    for line in ("license: apache-2.0", "base_model: lightonai/LightOnOCR-3-4B", "base_model_relation: adapter", "library_name: peft"):
        assert line in front
    assert BASE_REVISION in card and DISCLAIMER in card
    for s in caveats(_results()):
        assert s in card
    assert "+0.200" in card and "[+0.150, +0.250]" in card
    assert "| `prime_l` | 1 | 0 | 231 | not enough events to claim |" in card
    assert "## The problem" in card and "## Model details" in card and "## Training data" in card
    assert not re.search(r"\{\{[a-z_]+\}\}", card)
    assert "@@MODEL_NAME@@" in card


